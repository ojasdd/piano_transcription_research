"""Sheet music export utilities for LilyPond and notation representation."""
from typing import List, Dict, Any


PITCH_NAMES = ["c", "cis", "d", "dis", "e", "f", "fis", "g", "gis", "a", "ais", "b"]


def pitch_to_lilypond(pitch: int) -> str:
    """Convert MIDI pitch (21..108) to LilyPond note name."""
    note_idx = pitch % 12
    octave = (pitch // 12) - 1
    base_name = PITCH_NAMES[note_idx]

    # In LilyPond, octave 3 is base (e.g. c), octave 4 is c', octave 2 is c,
    if octave >= 4:
        return base_name + ("'" * (octave - 3))
    elif octave <= 2:
        return base_name + ("," * (3 - octave))
    else:
        return base_name


def notes_to_lilypond(notes: List[Dict[str, Any]], title: str = "Piano Transcription") -> str:
    """Convert transcription note events into a clean LilyPond score (.ly).
    
    Each note event is a dict: {'pitch': int, 'onset': float, 'offset': float, ...}
    Splits into treble clef (pitch >= 60) and bass clef (pitch < 60).
    """
    if not notes:
        return f"""\\version "2.22.0"
\\header {{
  title = "{title}"
  tagline = "Generated by Prior-Aware Piano Transcriber"
}}
\\score {{
  \\new PianoStaff <<
    \\new Staff = "upper" {{ \\clef treble \\time 4/4 r1 }}
    \\new Staff = "lower" {{ \\clef bass \\time 4/4 r1 }}
  >>
  \\layout {{ }}
  \\midi {{ }}
}}
"""

    treble_notes = []
    bass_notes = []

    for n in sorted(notes, key=lambda x: x["onset"]):
        pitch = int(n["pitch"])
        ly_note = pitch_to_lilypond(pitch)
        duration = max(0.05, float(n.get("offset", n["onset"] + 0.25)) - float(n["onset"]))
        
        # Approximate duration string: 4 for quarter, 8 for eighth, 2 for half, 1 for whole
        if duration >= 1.5:
            dur_str = "1"
        elif duration >= 0.75:
            dur_str = "2"
        elif duration >= 0.35:
            dur_str = "4"
        elif duration >= 0.18:
            dur_str = "8"
        else:
            dur_str = "16"

        entry = f"{ly_note}{dur_str}"
        if pitch >= 60:
            treble_notes.append(entry)
        else:
            bass_notes.append(entry)

    treble_body = " ".join(treble_notes) if treble_notes else "r1"
    bass_body = " ".join(bass_notes) if bass_notes else "r1"

    ly_content = f"""\\version "2.22.0"
\\header {{
  title = "{title}"
  subtitle = "Prior-Aware Frame Decoding"
  tagline = "Exported from Prior-Aware Piano Transcriber"
}}

\\score {{
  \\new PianoStaff <<
    \\new Staff = "upper" {{
      \\clef treble
      \\time 4/4
      {treble_body}
      \\bar "|."
    }}
    \\new Staff = "lower" {{
      \\clef bass
      \\time 4/4
      {bass_body}
      \\bar "|."
    }}
  >>
  \\layout {{ }}
  \\midi {{ }}
}}
"""
    return ly_content
